    private void btnShowScoresActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShowScoresActionPerformed
        // TODO add your handling code here:
        //ArrayList of integers to store scores
        ArrayList<Integer> scores = new ArrayList<>();
        //ArrayList of strings to store names
        ArrayList<String> names = new ArrayList<>();

        //Reads file containing fibonacci game scores and the names of those who achieved them. Sorts the lines into their respective ArrayLists
        FibonacciGame.importScores(scores, names, FibonacciGame.fileName);

        //Sorts ArrayLists in descending order
        FibonacciGame.sortScores(scores, names);

        //Outputs guessing games names and scores sorted in descending order
        for (int i = 0; i < scores.size(); i++) {
            txtOutput.append(names.get(i) + "\n");
            txtOutput.append(scores.get(i) + "\n");
        }
    }//GEN-LAST:event_btnShowScoresActionPerformed
