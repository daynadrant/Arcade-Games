    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        //Takes in user input
        String name = txtName.getText();
        //If input for name is equal, output their guessing game high score
        int score = GuessingGame.searchScores(GuessingGame.people, name, GuessingGame.gameName);
        if (score >= 0) {
            txtOutput.setText(name + "'s high score in Guessing Game is " + score);
        } else {
            txtOutput.setText("There is no high score in Guessing Game available for " + name);
        }
    }//GEN-LAST:event_btnSearchActionPerformed

