    private void btnContinueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContinueActionPerformed
        // TODO add your handling code here:
        try {
            //Read in user information
            int age = Integer.parseInt(txtAge.getText());
            String name = txtName.getText();
            if (age < 0) {
                throw new NumberFormatException();
            }

            new FrmMainMenu().setVisible(true);
            //Deserialize objects of "Person" from People.txt and place them in an ArrayList
            Person.readObjectFromFile(Game.people);

            //Set current player
            Game.player = Person.setPlayer(age, name, Game.people);

        } catch (NumberFormatException e) {
            txtOutput.setText("Invalid input! Your age must be a positive integer. Try again.");
        } catch (IOException e) {
            System.out.println(e);
        } catch (ClassNotFoundException e) {
            System.out.println(e);
        }
    }//GEN-LAST:event_btnContinueActionPerformed

