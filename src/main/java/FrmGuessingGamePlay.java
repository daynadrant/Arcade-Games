    private void btnCheckActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckActionPerformed
        // TODO add your handling code here:
        //Take in user input
        guess = txtGuess.getText();
        //Check if input is valud
        if (gg.checkInputValidity(guess)) {
            //Check if input matches answer
            int path = gg.play(score, Integer.parseInt(guess), number);
            //Input is correct
            if (path == 1) {
                txtGuess.setText("");
                txtOutput.setText(gg.winMessage(score, number));
                btnContinue.setVisible(true);
                lblGuess.setVisible(false);
                txtGuess.setVisible(false);
                btnCheck.setVisible(false);
                //Input is incorrect, but player has more guessees
            } else if (path == 2) {
                score = score - 50;
                if (number > Integer.parseInt(guess)) {
                    txtGuess.setText("");
                    txtOutput.setText("Too low!\nTry again.");
                } else {
                    txtGuess.setText("");
                    txtOutput.setText("Too high!\nTry again.");
                }
                //Input is incorrect, and player is out of guesses
            } else if (path == 3) {
                txtOutput.setText(gg.loseMessage(score, number));
                btnContinue.setVisible(true);
                lblGuess.setVisible(false);
                txtGuess.setVisible(false);
                btnCheck.setVisible(false);
            }
        } else {
            txtOutput.setText(gg.invalidInputMessage());
        }
    }//GEN-LAST:event_btnCheckActionPerformed

