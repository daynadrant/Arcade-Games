    private void btnCheckActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckActionPerformed
        // TODO add your handling code here:
        //Take in user input
        input = txtNumber.getText();
        //Check if input is valid
        if (fib.checkInputValidity(input)) {
            lblNumber.setText("Enter fibonacci number " + (number + 1) + ":");
            //Check if input matches answer
            int path = fib.play(score, Integer.parseInt(input), number);
            //Input is correct
            if (path == 1) {
                score = score + 50;
                txtNumber.setText("");
                txtOutput.setText(fib.winMessage(score, number));
                //Input is incorrect
            } else if (path == 2) {
                txtOutput.setText(fib.loseMessage(score, number));
                btnContinue.setVisible(true);
                lblNumber.setVisible(false);
                txtNumber.setVisible(false);
                btnCheck.setVisible(false);
            }
            number++;
        } else {
            txtOutput.setText(fib.invalidInputMessage());
        }
    }//GEN-LAST:event_btnCheckActionPerformed

