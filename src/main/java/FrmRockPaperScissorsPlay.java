    public void rockPaperScissorsTurnMessage() {
        //Check results
        int path = rps.play(score, choice, number);
        //If player beat opponent
        if (path == 1) {
            score = score + 50;
            txtOutput.setText(rps.winMessage(score, number));
            //If opponent beat player
        } else if (path == 2) {
            txtOutput.setText(rps.loseMessage(score, number));
            lblMove.setVisible(false);
            btnContinue.setVisible(true);
            btnRock.setVisible(false);
            btnScissors.setVisible(false);
            btnPaper.setVisible(false);
            //If there was a tie
        } else {
            txtOutput.setText(rps.tieMessage(score, number));
        }
    }

